std::string service_exposure_label(std::uint16_t port, const std::string& transport) {
    auto profile = lookup_service_profile(port, transport);
    if (!profile) {
        return "unknown service exposure";
    }
    return std::string(profile->service) + " [" + profile->risk + "] " + profile->exposure;
}
std::string dns_type_signal_label(std::uint16_t type) {
    auto profile = lookup_dns_type_profile(type);
    if (!profile) {
        return "unknown DNS type";
    }
    return std::string(profile->mnemonic) + " [" + profile->signal + "] " + profile->meaning;
}
